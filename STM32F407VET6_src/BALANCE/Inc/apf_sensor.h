/*
 * apf_sensor.h — 三路测距传感器数据融合模块头文件
 * 【用途】
 *   将三路测距传感器（前方0°、左前+45°、右前-45°）的距离读数，
 *   融合为一个虚拟障碍物坐标（车身坐标系），再转换到世界坐标系，
 *   供 apf_follow() 用作障碍物输入。
 *
 * 【传感器硬件假设】
 *   - 前方传感器：安装在车头正中，朝向正前方（0°）
 *   - 左侧传感器：安装在车头偏左，朝向左前方（+45°）
 *   - 右侧传感器：安装在车头偏右，朝向右前方（-45°）
 *   - 传感器类型：超声波 HC-SR04 / TOF 激光测距 VL53L0X 等均可
 *
 * 【坐标约定】
 *   车身坐标系：车头方向为 +X，车左侧为 +Y（右手系）
 *   世界坐标系：与 APF_Car 的世界坐标一致
 */

#ifndef __APF_SENSOR_H
#define __APF_SENSOR_H

#include "apf.h"   /* 使用 APF_Car, APF_CircObs, APF_Vec2 等类型 */

/* ============================================================
 *  传感器物理安装位置（车身坐标系，单位：米）
 *
 *  这些值需要根据实际安装位置标定：
 *    SENSOR_FRONT_X — 前方传感器距车中心的前后距离（前为正）
 *    SENSOR_FRONT_Y — 前方传感器距车中心的左右偏移（左为正）
 *
 *  示例（小车全长约 25cm，宽约 15cm）：
 *    前传感器装在车头最前端，左右居中
 *    左/右传感器装在车头偏后一点，左右各偏 6cm
 * ============================================================ */
#define SENSOR_FRONT_X   0.12f   /* 前方传感器 X 坐标（车头方向） */
#define SENSOR_FRONT_Y   0.00f   /* 前方传感器 Y 坐标（左右居中） */
#define SENSOR_LEFT_X    0.08f   /* 左侧传感器 X 坐标            */
#define SENSOR_LEFT_Y    0.06f   /* 左侧传感器 Y 坐标（左偏6cm） */
#define SENSOR_RIGHT_X   0.08f   /* 右侧传感器 X 坐标            */
#define SENSOR_RIGHT_Y  -0.06f   /* 右侧传感器 Y 坐标（右偏6cm） */

/* ============================================================
 *  传感器波束角预计算值
 *
 *  前方 = 0°, 左侧 = +45°, 右侧 = -45°
 *  使用预计算常量避免在中断中调用 cosf/sinf，提升效率
 * ============================================================ */
#define COS_0    1.0f
#define SIN_0    0.0f
#define COS_45   0.70710678f   /* cos( 45°) = √2/2 */
#define SIN_45   0.70710678f
#define COS_N45  0.70710678f
#define SIN_N45 -0.70710678f

/* ============================================================
 *  传感器参数
 * ============================================================ */
#define SENSOR_MAX_RANGE     2.0f    /* 传感器最大有效量程(m)，超出视为无效 */


/* ============================================================
 *  传感器融合结果数据结构
 * ============================================================ */
typedef struct {
    float x;           /* 虚拟障碍物 X 坐标（车身坐标系，米） */
    float y;           /* 虚拟障碍物 Y 坐标（车身坐标系，米） */
    float confidence;  /* 置信度 0.0~1.0（三路都有检测且近距离时最高） */
    int   valid;       /* 1 = 有效检测，0 = 无检测 */
} APF_SensorObs;

/* ============================================================
 *  函数声明
 * ============================================================ */

/*
 * APF_SensorFusion() — 三路测距传感器数据融合
 *
 * 参数:
 *   dist_front — 前方传感器距离读数(m)，<=0 或 >= MAX_RANGE 视为无效
 *   dist_left  — 左侧传感器距离读数(m)
 *   dist_right — 右侧传感器距离读数(m)
 *
 * 返回:
 *   APF_SensorObs — 虚拟障碍物在车身坐标系中的位置及置信度
 */
APF_SensorObs APF_SensorFusion(float dist_front,
                                float dist_left,
                                float dist_right);

/*
 * APF_SensorToCircObs() — 将传感器融合结果转换为世界坐标系圆形障碍物
 *
 * 参数:
 *   obs  — 传感器融合结果（车身坐标系）
 *   car  — 小车当前位姿（世界坐标系）
 *   out  — 输出：世界坐标系下的圆形障碍物数组
 *   max_obs — out 数组的最大容量
 *
 * 返回:
 *   实际写入的障碍物数量（0 或 1）
 */
int APF_SensorToCircObs(const APF_SensorObs *obs,
                         const APF_Car *car,
                         APF_CircObs *out,
                         int max_obs);

#endif /* __APF_SENSOR_H */
